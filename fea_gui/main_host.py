"""Typed host of the main window mixins - for the type checker only (nothing imports this module at run time).

`MainWindow` is put together from mixins (`chrome.py`, `ipc_bridge.py`, `main_*.py`) that use attributes and methods of the
window and of each other through `self`. Every mixin therefore derives, for the type checker only, from `MainWindowHost`:

    if TYPE_CHECKING:
        from .main_host import MainWindowHost as _Base
    else:
        _Base = object

so at run time the bases and the MRO of `MainWindow` stay what they were, and the checker sees the declarations below. It is a plain
class, not a `Protocol`: it derives from `QMainWindow`, so the Qt methods used through `self` (statusBar, setCentralWidget ...) resolve
without being declared again (the checker rejects a Protocol that derives from QMainWindow), and one base class per mixin replaces a
`self: Protocol` annotation on each of the ~370 methods.

What is declared: only the members that a mixin uses and does not define itself. Each mixin's own members are still inferred
from its code (they come first in the MRO). `MainWindow.__init__` and the mixins assign the attributes, so the checker verifies
every assignment against the declared type here. A signature that drifts from the implementation is reported by
`reportIncompatibleMethodOverride` (switched on per file in the mixins).

When a mixin starts to use another member of the window or of a sibling mixin, declare it here (the checker reports
`Cannot access attribute ... for class "<Mixin>"`). The generation of the first version and the derivation of the names
(AST scan of the `self.<name>` uses of every mixin) are described in `docs/projekt/F16_plan_1_4_4.md`, "As built".
"""
