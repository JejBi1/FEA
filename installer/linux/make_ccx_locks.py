#!/usr/bin/env python3
"""Regenerates installer/linux/ccx_toolchain.lock and ccx_deps.lock – the exact conda-forge packages (URL, SHA-256, MD5 from the repodata)
of the two environments that build_ccx.sh creates:

  TC_SPEC    the compilers and tools that build CalculiX (gcc, gfortran, cmake, patchelf, ...) – their runtime libraries (libgomp,
             libquadmath) are shipped next to ccx_spooles;
  DEPS_SPEC  OpenBLAS, SCOTCH, hwloc, ... for the PaStiX build (ccx_pastix) – shipped next to it.

The specs are read from build_ccx.sh (one source). build_ccx.sh does not resolve anything: it downloads exactly the packages of the lock,
checks every SHA-256 and creates the environment from an @EXPLICIT list (micromamba also checks the MD5). A new version of a package = a new
lock = a reviewed change. Run it (on any machine with micromamba; the solver runs for linux-64 with a virtual glibc 2.35):

    python installer/linux/make_ccx_locks.py [--micromamba PATH]

Lock file format: `#` lines, then `<sha256> <md5> <url>` per package in the order micromamba would link them.
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPT = HERE / "build_ccx.sh"
LOCKS = {"TC_SPEC": HERE / "ccx_toolchain.lock", "DEPS_SPEC": HERE / "ccx_deps.lock"}
CHANNEL = "https://conda.anaconda.org/conda-forge/"


def read_spec(name: str, text: str | None = None) -> str:
    """The value of `NAME="..."` in build_ccx.sh."""
    text = SCRIPT.read_text(encoding="utf-8") if text is None else text
    m = re.search(rf'^{name}="([^"]+)"', text, re.MULTILINE)
    if not m:
        raise SystemExit(f"{SCRIPT.name}: {name} not found")
    return m.group(1)


def parse_lock(path: Path) -> tuple[str, list[tuple[str, str, str]]]:
    """(spec from the header, [(sha256, md5, url)]) of a lock file. ValueError for a malformed file."""
    spec, rows = "", []
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("# spec: "):
            spec = line[len("# spec: "):]
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) != 3 or not re.fullmatch(r"[0-9a-f]{64}", parts[0]) or not re.fullmatch(r"[0-9a-f]{32}", parts[1]) \
                or not parts[2].startswith(CHANNEL) or not re.search(r"\.(conda|tar\.bz2)$", parts[2]):
            raise ValueError(f"{path.name}:{n}: expected '<sha256> <md5> <conda-forge URL>'")
        rows.append((parts[0], parts[1], parts[2]))
    return spec, rows


def solve(micromamba: str, specs: list[str]) -> list[dict]:
    """The packages that micromamba would install for the specs (dry run, JSON), in linking order."""
    with tempfile.TemporaryDirectory() as tmp:
        env = dict(os.environ, MAMBA_ROOT_PREFIX=str(Path(tmp) / "root"), CONDA_OVERRIDE_GLIBC="2.35", PYTHONIOENCODING="utf-8")
        r = subprocess.run([micromamba, "create", "-y", "--dry-run", "--json", "-p", str(Path(tmp) / "env"), "-c", "conda-forge", "--no-rc",
                            "--platform", "linux-64", *specs], env=env, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0 or "{" not in r.stdout:
        raise SystemExit(f"micromamba ended with code {r.returncode}: {r.stderr[-600:] or r.stdout[-600:]}")
    link = json.loads(r.stdout[r.stdout.index("{"):]).get("actions", {}).get("LINK", [])
    if not link:
        raise SystemExit("micromamba returned no packages")
    for x in link:
        if not (x.get("url") or "").startswith(CHANNEL) or not x.get("sha256") or not x.get("md5"):
            raise SystemExit(f"package {x.get('name')}: repodata has no URL / SHA-256 / MD5")
    return link


def write_lock(path: Path, spec: str, link: list[dict], version: str) -> None:
    lines = [f"# conda-forge linux-64 packages of installer/linux/build_ccx.sh – generated by installer/linux/make_ccx_locks.py "
             f"({datetime.date.today().isoformat()}, micromamba {version}); do not edit by hand",
             f"# spec: {spec}", "# <sha256> <md5> <url>"]
    lines += [f"{x['sha256']} {x['md5']} {x['url']}" for x in link]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--micromamba", default=shutil.which("micromamba") or "micromamba", help="path to micromamba (2.x)")
    a = ap.parse_args()
    version = subprocess.run([a.micromamba, "--version"], capture_output=True, text=True).stdout.strip()
    for name, path in LOCKS.items():
        spec = read_spec(name)
        link = solve(a.micromamba, spec.split())
        write_lock(path, spec, link, version)
        print(f"{path.name}: {len(link)} packages ({name} = {spec})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
